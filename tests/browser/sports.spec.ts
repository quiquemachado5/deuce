import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('home shows a recent tournament, photography and verified discoveries',async({page})=>{
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/');
  const hero=page.locator('.ds-hero-record');
  await expect(hero.getByRole('heading',{level:2})).not.toBeEmpty();
  await expect(hero).toContainText('Ganador del último encuentro');
  await expect(hero.getByRole('link',{name:'Ver el partido',exact:true})).toHaveAttribute('href',/\/match\//);
  await expect(hero.locator('.ds-hero-court img')).toBeVisible();
  await expect(page.locator('.ds-results-list .nc-match-row')).toHaveCount(5);
  const discoveries=page.getByRole('region',{name:'Siempre hay otro dato.'});
  await expect(discoveries.locator('.ds-story')).toHaveCount(6);
  await expect(discoveries.locator('.ds-story').first()).toContainText('Andy Murray');
  const initial=await discoveries.locator('.ds-discovery-number').innerText();
  await discoveries.getByRole('button',{name:'Otro dato'}).click();
  await expect(discoveries.locator('.ds-discovery-number')).not.toHaveText(initial);
  await expect(discoveries.locator('.ds-discovery-copy>a')).toHaveAttribute('href',/\/records\?dato=/);
  await page.screenshot({path:test.info().outputPath('home-desktop.png')});
  for(const width of [390,320]){
    await page.setViewportSize({width,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  }
  const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','best-practice']).analyze();
  expect(axe.violations).toEqual([]);
  await page.screenshot({path:test.info().outputPath('home-mobile.png')});
});
test('tiebreaks stay inline and five sets fit in one readable strip',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/match/archive-148401');
  await expect(page.locator('.ry-mobile-score-line')).toContainText('6–7(5), 6–7(8)');
  await expect(page.locator('.ry-scoreboard sup')).toHaveCount(0);
  await expect(page.locator('.ry-set-tiebreak').first()).toHaveText('(5)');
  const picker=page.getByRole('group',{name:'Seleccionar set'}).first();
  const sets=picker.getByRole('button');
  await expect(sets).toHaveCount(5);
  const first=await sets.first().boundingBox(),last=await sets.last().boundingBox();
  expect(first).not.toBeNull();
  expect(last).not.toBeNull();
  expect(Math.abs(first!.y-last!.y)).toBeLessThan(2);
  await sets.nth(2).click();
  await expect(sets.nth(2)).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.ds-set-summary')).toContainText('Roger Federer ganó el set');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('.ds-match-story').first().scrollIntoViewIfNeeded();
  await page.screenshot({path:test.info().outputPath('match-story-mobile.png')});
  await page.setViewportSize({width:1440,height:900});
  await expect(page.locator('.ry-set-tiebreak').first()).toBeVisible();
  expect(await page.locator('.ry-set-tiebreak').first().evaluate(el=>getComputedStyle(el).verticalAlign)).toBe('baseline');
});
test('verified game flow has readable axes, moments and an equivalent table',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/match/live-203807');
  const flow=page.locator('.ry-game-flow');
  await expect(flow).toBeVisible();
  await expect(flow.locator('.ry-game-flow-axis span')).toHaveCount(3);
  await expect(flow.getByRole('img')).toHaveAttribute('aria-label',/eje horizontal de 0 a 20, eje vertical/);
  await flow.getByText('Ver juegos en tabla').click();
  await expect(flow.getByRole('table',{name:/Juegos cerrados y verificados/})).toBeVisible();
  await expect(flow.locator('tbody tr').first()).toContainText('juego');
  const moment=flow.getByRole('button',{name:/Break de/}).first();
  await moment.click();
  await expect(moment).toHaveAttribute('aria-pressed','true');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
