import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('daily coverage explains queries, categories and publication gates on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/cobertura');
  await expect(page.getByRole('heading', { name: 'Actividad diaria' })).toBeVisible();
  await expect(page.getByRole('list', { name: 'Actividad diaria de la API' })).toBeAttached();
  await expect(page.getByRole('list', { name: 'Actividad diaria de la API' }).getByText('ATP', { exact: true }).first()).toBeVisible();
  await expect(page.getByRole('list', { name: 'Actividad diaria de la API' }).getByText('WTA', { exact: true }).first()).toBeVisible();
  await expect(page.locator('.coverage-hero-stats dt').filter({ hasText: /^Partidos ATP$/ })).toBeVisible();
  await expect(page.locator('.coverage-hero-stats dt').filter({ hasText: /^Partidos WTA$/ })).toBeVisible();
  await expect(page.getByText('ATP 500', { exact: true })).toBeVisible();
  await expect(page.getByText('ATP 250', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze();
  expect(audit.violations).toEqual([]);
  await page.getByRole('heading', { name: 'Actividad diaria' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/deuce-daily-coverage-mobile.png' });
  await page.goto('/cobertura/revision');
  await expect(page).toHaveURL(/\/cobertura#calidad$/);
  await expect(page.getByRole('heading', { name: 'Lo incompleto no se publica.' })).toBeVisible();
  await expect(page.getByText('resultados incompletos publicados')).toBeVisible();
  await page.getByText('Qué ocurre cuando una fuente llega incompleta').click();
  await expect(page.getByText(/Nunca se inventa un marcador/)).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByText('Qué ocurre cuando una fuente llega incompleta').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/deuce-quality-review-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.goto('/cobertura');
  await page.getByRole('heading', { name: 'Actividad diaria' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/deuce-daily-coverage-desktop.png' });
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()).violations).toEqual([]);
});
